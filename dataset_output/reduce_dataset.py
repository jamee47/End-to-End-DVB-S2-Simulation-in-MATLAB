"""
reduce_dataset.py
-----------------
Reads the full DVB-S2 CSV dataset generated by dvbs2_dataset_generator.m,
drops the raw data symbol columns (data_re_*, data_im_*) which are large
and not needed for pilot-based channel estimation, and saves a lean version.

Output files
------------
  dvbs2_pilot_dataset.csv   — reduced CSV (pilots + metadata only)
  dvbs2_pilot_dataset.npz   — NumPy archive (ready for PyTorch / TensorFlow)

Retained column groups
----------------------
  plheader_re / im   : PLHEADER complex symbols     [90 each]
  pilot_re / im      : raw received pilot symbols   [Np each]
  H_LS_re / im       : LS estimate per pilot block  [K each]
  H_true_re / im     : true channel coefficient     [1 each]
  snr_dB             : Es/No in dB                  [1]
  nVar               : noise variance estimate       [1]
  modcod             : MODCOD index                  [1]
  Kfactor_dB         : Rician K-factor in dB        [1]

Dropped column groups
---------------------
  data_re_*          : data symbol real parts       (~32 400 cols)
  data_im_*          : data symbol imaginary parts  (~32 400 cols)
"""

import os
import time
import numpy as np
import pandas as pd

# ── Configuration ──────────────────────────────────────────────────────────
INPUT_CSV   = 'dvbs2_channel_dataset.csv'
OUTPUT_CSV  = 'dvbs2_pilot_dataset.csv'
OUTPUT_NPZ  = 'dvbs2_pilot_dataset.npz'
CHUNK_SIZE  = 50          # rows per chunk (keep low — rows are very wide)

# ── Step 1: Read header to identify columns ────────────────────────────────
print('=' * 60)
print('DVB-S2 Dataset Reducer')
print('=' * 60)

if not os.path.exists(INPUT_CSV):
    raise FileNotFoundError(f"Input file not found: {INPUT_CSV}")

print(f'\n[1] Reading column names from {INPUT_CSV} ...')
with open(INPUT_CSV, 'r') as f:
    header_line = f.readline().strip()

all_cols = header_line.split(',')
total_cols = len(all_cols)
print(f'    Total columns in input : {total_cols:,}')

# ── Step 2: Classify columns ───────────────────────────────────────────────
def col_group(name):
    if name.startswith('plheader_re'): return 'plheader_re'
    if name.startswith('plheader_im'): return 'plheader_im'
    if name.startswith('data_re'):     return 'data_re'      # ← DROP
    if name.startswith('data_im'):     return 'data_im'      # ← DROP
    if name.startswith('pilot_re'):    return 'pilot_re'
    if name.startswith('pilot_im'):    return 'pilot_im'
    if name.startswith('H_LS_re'):     return 'H_LS_re'
    if name.startswith('H_LS_im'):     return 'H_LS_im'
    return 'metadata'                                        # scalars

drop_prefixes = ('data_re_', 'data_im_','plheader_re','plheader_im','H_LS_re','H_LS_im')
keep_cols     = [c for c in all_cols if not c.startswith(drop_prefixes)]
drop_cols     = [c for c in all_cols if     c.startswith(drop_prefixes)]

# Group counts for summary
from collections import Counter
kept_groups    = Counter(col_group(c) for c in keep_cols)
dropped_groups = Counter(col_group(c) for c in drop_cols)

print(f'\n[2] Column classification:')
print(f'    {"Group":<20} {"Keep":>8} {"Drop":>8}')
print(f'    {"-"*38}')
all_groups = sorted(set(list(kept_groups) + list(dropped_groups)))
for g in all_groups:
    print(f'    {g:<20} {kept_groups.get(g,0):>8,} {dropped_groups.get(g,0):>8,}')
print(f'    {"-"*38}')
print(f'    {"TOTAL":<20} {len(keep_cols):>8,} {len(drop_cols):>8,}')

# ── Step 3: Count rows ─────────────────────────────────────────────────────
print(f'\n[3] Counting rows in {INPUT_CSV} ...')
with open(INPUT_CSV, 'r') as f:
    num_rows = sum(1 for _ in f) - 1      # subtract header
print(f'    Rows (frames): {num_rows:,}')

# ── Step 4: Chunked read → write reduced CSV ───────────────────────────────
print(f'\n[4] Processing in chunks of {CHUNK_SIZE} rows ...')
print(f'    Writing reduced CSV -> {OUTPUT_CSV}')

# usecols filter avoids loading dropped columns into memory entirely
usecols_filter = lambda col: not col.startswith(drop_prefixes)

t0            = time.time()
rows_done     = 0
first_chunk   = True

# Collect all chunks into a list for NPZ (feasible since reduced dataset is small)
all_chunks = []

for chunk in pd.read_csv(
        INPUT_CSV,
        usecols  = usecols_filter,
        chunksize= CHUNK_SIZE,
        dtype    = np.float32):          # float32 halves memory vs float64

    # Write CSV — header only on first chunk
    chunk.to_csv(OUTPUT_CSV,
                 mode   = 'w' if first_chunk else 'a',
                 header = first_chunk,
                 index  = False)
    first_chunk = False
    all_chunks.append(chunk)

    rows_done += len(chunk)
    elapsed    = time.time() - t0
    pct        = 100 * rows_done / num_rows if num_rows > 0 else 0
    print(f'    {rows_done:>6}/{num_rows} rows  '
          f'[{pct:5.1f}%]  {elapsed:6.1f}s', end='\r')

print()   # newline after progress

# ── Step 5: Save NPZ ───────────────────────────────────────────────────────
print(f'\n[5] Building NumPy arrays and saving -> {OUTPUT_NPZ}')

df = pd.concat(all_chunks, ignore_index=True)

# Extract named groups as separate arrays for easy use in ML frameworks
def get_cols(prefix):
    """Return numpy array for all columns starting with prefix."""
    cols = [c for c in df.columns if c.startswith(prefix)]
    return df[cols].values.astype(np.float32) if cols else np.array([])

plheader_re = get_cols('plheader_re')   # [N × 90]
plheader_im = get_cols('plheader_im')   # [N × 90]
pilot_re    = get_cols('pilot_re')      # [N × Np]
pilot_im    = get_cols('pilot_im')      # [N × Np]
H_LS_re     = get_cols('H_LS_re')       # [N × K]
H_LS_im     = get_cols('H_LS_im')       # [N × K]

H_true_re   = df['H_true_re'].values.astype(np.float32)   # [N]
H_true_im   = df['H_true_im'].values.astype(np.float32)   # [N]
snr_dB      = df['snr_dB'].values.astype(np.float32)
nVar        = df['nVar'].values.astype(np.float32)
modcod      = df['modcod'].values.astype(np.int32)
rainAtt_dB  = df['rainAtt_dB'].values.astype(np.float32)

# Convenience: recombine real+imag into complex pilot sequence per block
# H_LS_complex: [N × K] complex — direct BLSTM input
H_LS_complex    = H_LS_re    + 1j * H_LS_im          # [N × K]
H_true_complex  = H_true_re  + 1j * H_true_im         # [N]

# PLHEADER complex
plheader_complex = plheader_re + 1j * plheader_im      # [N × 90]

# Raw pilot complex
pilot_complex   = pilot_re + 1j * pilot_im             # [N × Np]

np.savez_compressed(
    OUTPUT_NPZ,
    # ── Raw received symbols ──────────────────────────
    plheader_re      = plheader_re,        # [N × 90]
    plheader_im      = plheader_im,        # [N × 90]
    pilot_re         = pilot_re,           # [N × Np]
    pilot_im         = pilot_im,           # [N × Np]
    # ── Channel estimates ─────────────────────────────
    H_LS_re          = H_LS_re,            # [N × K]
    H_LS_im          = H_LS_im,            # [N × K]
    # ── Labels ───────────────────────────────────────
    H_true_re        = H_true_re,          # [N]
    H_true_im        = H_true_im,          # [N]
    # ── Metadata ─────────────────────────────────────
    snr_dB           = snr_dB,             # [N]
    nVar             = nVar,               # [N]
    modcod           = modcod,             # [N]
    rainAtt_dB       = rainAtt_dB,        # [N]
)

# ── Step 6: Summary ────────────────────────────────────────────────────────
csv_size_mb = os.path.getsize(OUTPUT_CSV)  / 1e6
npz_size_mb = os.path.getsize(OUTPUT_NPZ) / 1e6
inp_size_mb = os.path.getsize(INPUT_CSV)  / 1e6

print(f'\n{"=" * 60}')
print(f'  Done in {time.time() - t0:.1f}s')
print(f'{"=" * 60}')
print(f'  Input  CSV : {inp_size_mb:>8.1f} MB   ({total_cols:,} cols)')
print(f'  Output CSV : {csv_size_mb:>8.1f} MB   ({len(keep_cols):,} cols)')
print(f'  Output NPZ : {npz_size_mb:>8.1f} MB   (compressed)')
print(f'  Reduction  : {100*(1 - csv_size_mb/inp_size_mb):.1f}% smaller')
print(f'{"=" * 60}')

print(f'\nNPZ array shapes:')
print(f'  plheader  (re/im)  : {plheader_re.shape}  /  {plheader_im.shape}')
print(f'  pilot     (re/im)  : {pilot_re.shape}  /  {pilot_im.shape}')
print(f'  H_LS      (re/im)  : {H_LS_re.shape}  /  {H_LS_im.shape}')
print(f'  H_true    (re/im)  : {H_true_re.shape}  /  {H_true_im.shape}')
print(f'  snr_dB             : {snr_dB.shape}')
print(f'  nVar               : {nVar.shape}')
print(f'  modcod             : {modcod.shape}')
print(f'  rainAtt_dB         : {rainAtt_dB.shape}')

print(f'\nUsage in Python:')
print(f'  data = np.load("{OUTPUT_NPZ}")')
print(f'  X    = data["H_LS_re"] + 1j * data["H_LS_im"]  # [N x K] input')
print(f'  Y    = data["H_true_re"] + 1j * data["H_true_im"]  # [N] label')
